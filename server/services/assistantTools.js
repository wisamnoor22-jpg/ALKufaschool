const normalizeArabic = (value = "") =>
  String(value)
    .toLowerCase()
    .replace(/[أإآ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/[ًٌٍَُِّْـ]/g, "")
    .replace(/[^\p{L}\p{N}\s]/gu, " ")
    .replace(/\s+/g, " ")
    .trim();

const findLocalAnswer = (message) => {
  const normalizedMessage = normalizeArabic(message);
  if (!normalizedMessage) return null;

  for (const faq of FAQS) {
    const matched = faq.keywords.some((keyword) =>
      normalizedMessage.includes(normalizeArabic(keyword))
    );

    if (matched) {
      return {
        answer: faq.answer,
        suggestedPath: faq.path || null,
        suggestedLabel:
          PROGRAM_SECTIONS.find((section) => section.path === faq.path)?.title || null,
      };
    }
  }

  return null;
};

const PROGRAM_GUIDE = PROGRAM_SECTIONS.map(
  (section) => `- ${section.title} (${section.path}): ${section.description}`
).join("\n");

const FAQ_GUIDE = FAQS.map(
  (faq) => `س: ${faq.question}\nج: ${faq.answer}`
).join("\n\n");

